/// Returns the glyph for `c`. Characters outside printable ASCII show as `?`.
pub fn glyph(c: char) -> &'static [u8; 5] {
    let code = c as u32;
    if code >= FIRST as u32 && code <= LAST as u32 {
        &GLYPHS[(code - FIRST as u32) as usize]
    } else {
        &GLYPHS[(b'?' - FIRST) as usize]
    }
}

/// Width in pixels of `s` when drawn with this font.
pub fn text_width(s: &str) -> i32 {
    let n = s.chars().count() as i32;
    if n == 0 { 0 } else { n * ADVANCE - 1 }
}

/// Replaces common typographic characters with ASCII look-alikes, so track titles
/// with curly quotes or dashes still read well on the LCD.
pub fn to_lcd(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '\u{2018}' | '\u{2019}' | '\u{00B4}' => '\'',
            '\u{201C}' | '\u{201D}' => '"',
            '\u{2013}' | '\u{2014}' | '\u{2212}' => '-',
            '\u{2026}' => '.',
            '\u{00A0}' => ' ',
            'À'..='Å' | 'à'..='å' => if c.is_uppercase() { 'A' } else { 'a' },
            'È'..='Ë' | 'è'..='ë' => if c.is_uppercase() { 'E' } else { 'e' },
            'Ì'..='Ï' | 'ì'..='ï' => if c.is_uppercase() { 'I' } else { 'i' },
            'Ò'..='Ö' | 'ò'..='ö' | 'Ø' | 'ø' => if c.is_uppercase() { 'O' } else { 'o' },
            'Ù'..='Ü' | 'ù'..='ü' => if c.is_uppercase() { 'U' } else { 'u' },
            'Ñ' => 'N',
            'ñ' => 'n',
            'Ç' => 'C',
            'ç' => 'c',
            'ß' => 's',
            _ => c,
        })
        .collect()
}
