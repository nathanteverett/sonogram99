pub struct Palette {
    pub skin: &'static Skin,
    /// Bar gradient from bottom (0) to top (255).
    pub bars: [Rgb; 256],
    /// Heat map from silence (0) to full scale (255).
    pub heat: [Rgb; 256],
    /// Glow gradient from deep (0) to hot (255).
    pub glow: [Rgb; 256],
}

impl Palette {
    pub fn new(index: usize) -> Self {
        let skin = &SKINS[index % SKINS.len()];
        Palette { skin, bars: lut(skin.bars), heat: lut(skin.heat), glow: lut(skin.glow) }
    }

    #[inline]
    pub fn bar(&self, v: f32) -> Rgb {
        self.bars[(v.clamp(0.0, 1.0) * 255.0) as usize]
    }

    #[inline]
    pub fn heat(&self, v: f32) -> Rgb {
        self.heat[(v.clamp(0.0, 1.0) * 255.0) as usize]
    }

    #[inline]
    pub fn glow(&self, v: f32) -> Rgb {
        self.glow[(v.clamp(0.0, 1.0) * 255.0) as usize]
    }
}

fn lut(stops: &[Rgb]) -> [Rgb; 256] {
    let mut out = [[0u8; 3]; 256];
    let n = stops.len() - 1;
    for (i, slot) in out.iter_mut().enumerate() {
        let p = i as f32 / 255.0 * n as f32;
        let k = (p.floor() as usize).min(n - 1);
        *slot = crate::canvas::mix(stops[k], stops[k + 1], p - k as f32);
    }
    out
}
